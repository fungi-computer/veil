// Generate src/redaction-rules.generated.ts from vendor/gitleaks.toml, after
// checking every rule compiles on RE2. The module is committed: the App
// Publisher compiles Veil from a captured commit with tsc alone, so the rule
// table is source, not a build output. The package test fails while the
// committed module disagrees with the vendored rules.
//
// `pnpm run generate:redaction-rules` after updating vendor/gitleaks.toml;
// `--check` validates rules read from stdin and writes nothing.
import { readFile, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { format, resolveConfig } from "prettier";
import { parse } from "smol-toml";
import { RE2JS } from "re2js";

const root = new URL("../", import.meta.url);
const output = new URL("src/redaction-rules.generated.ts", root);

/** Parse gitleaks TOML and refuse any rule RE2 cannot compile. */
function validatedRules(toml) {
  const config = parse(toml);
  const failures = [];
  function compilePattern(source, id) {
    try {
      return RE2JS.compile(source);
    } catch (error) {
      console.error(`gitleaks rule ${id} could not compile:`, error);
      failures.push(id);
      return undefined;
    }
  }
  function validatePatterns(value, id) {
    for (const [key, field] of Object.entries(value)) {
      if (["regex", "path"].includes(key)) {
        compilePattern(field, `${id} (${key})`);
      } else if (["regexes", "paths"].includes(key)) {
        for (const pattern of field) {
          compilePattern(pattern, `${id} (${key})`);
        }
      } else if (key === "allowlists") {
        for (const allowlist of field) validatePatterns(allowlist, id);
      }
    }
  }
  validatePatterns(config.allowlist, "global allowlist");
  for (const rule of config.rules) {
    validatePatterns(rule, rule.id);
    if (rule.regex === undefined && rule.path === undefined)
      failures.push(`${rule.id}: neither content regex nor path rule`);
    if (rule.regex !== undefined && rule.secretGroup !== undefined) {
      const expression = compilePattern(rule.regex, rule.id);
      if (expression && rule.secretGroup > expression.groupCount())
        failures.push(`${rule.id}: secretGroup exceeds capture groups`);
    }
  }
  if (failures.length > 0) {
    throw new Error(
      `gitleaks rules could not compile:\n${failures.join("\n")}`,
    );
  }
  return config;
}

/** The generated module's text for the vendored gitleaks rules now. */
export async function renderRedactionRules() {
  const config = validatedRules(
    await readFile(new URL("vendor/gitleaks.toml", root), "utf8"),
  );
  const source = [
    "// Generated by scripts/generate-redaction-rules.mjs from vendor/gitleaks.toml. Do not edit.",
    "/** gitleaks' default rules, decoded by the redactor on first use. */",
    `export const configuration = ${JSON.stringify(config)};`,
    "",
  ].join("\n");
  const file = fileURLToPath(output);
  const options = { ...(await resolveConfig(file)), filepath: file };
  // A few gitleaks rule patterns match their own text, so a secret scan of
  // this module reports gitleaks' own rule as a leak. Mark exactly those
  // pattern lines with gitleaks' inline allow comment; nothing else is allowed.
  const selfMatching = new Set(
    config.rules
      .filter(
        (rule) =>
          rule.regex !== undefined &&
          RE2JS.compile(rule.regex).matcher(rule.regex).find(),
      )
      .map((rule) => `regex: ${JSON.stringify(rule.regex)},`),
  );
  const marked = new Set();
  const lines = (await format(source, options)).split("\n").map((line) => {
    if (!selfMatching.has(line.trim())) return line;
    marked.add(line.trim());
    return `${line} //gitleaks:allow`;
  });
  for (const line of selfMatching)
    if (!marked.has(line))
      throw new Error(`Self-matching rule pattern not on one line: ${line}`);
  return format(lines.join("\n"), options);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const { values } = parseArgs({
    options: { check: { type: "boolean", default: false } },
  });
  if (values.check) {
    const config = validatedRules(readFileSync(0, "utf8"));
    console.log(`Validated ${config.rules.length} gitleaks rules with re2js.`);
  } else {
    await writeFile(output, await renderRedactionRules());
  }
}
